"""strip_gte_msc02.py -- libgte MSC02.obj: InvSquareRoot (head, @0+140) and MatrixNormal (tail, @448+240), Sony GTE assembly
retail's link removed.  Lines generated by strip_asm_gen.py from the PsyQ 4.3 object."""
import json
import sys

sys.path.insert(0, 'C:/Temp/nfs4-decomp/scratchpad/psyq_pipe')
import strip_asm_gen as G

R = 'C:/Temp/nfs4-decomp/'
NL = chr(10)
p = R + 'recon/syslib/psx/libgte/MSC02.c'
s = open(p, encoding='utf-8').read()
inv = G.gen('LIBGTE', 'MSC02', 'InvSquareRoot', 'VectorNormalS', {'SECT(.data)+0x14': 'D_8013485C'})
mat = G.gen('LIBGTE', 'MSC02', 'MatrixNormal', None, {'SECT(.text)+0x100': '_VectorNormalSS_kernel'})
if 'gte_thunk.h' not in s:
    import re
    inc = [m for m in re.finditer(r'^#include [^\n]*\n', s, re.M)]
    pos = inc[-1].end() if inc else s.index('__asm__(')
    s = s[:pos] + '#include "../../../lib/gte_thunk.h"' + NL + s[pos:]
m = '/* MSC02.obj .data 0x8013485C..0x801349E8'
assert s.count(m) == 1
blk = ('/* MSC02.obj head + tail (LINK-STRIPPED): InvSquareRoot @0 and MatrixNormal @448 -- retail\'s object text is exactly' + NL +
       ' * VectorNormalS .. VectorNormalSS.  Sony GTE assembly; the lines are generated from the PsyQ 4.3 object' + NL +
       ' * (scratchpad/psyq_pipe/strip_asm_gen.py): `.word` = GTE commands, D_8013485C = the reciprocal-sqrt table below. */' + NL +
       'extern short D_8013485C[];' + NL + G.macro('InvSquareRoot', inv) + G.macro('MatrixNormal', mat) + NL)
s = s.replace(m, blk + m)
open(p, 'w', encoding='utf-8', newline='').write(s)
jf = json.load(open(R + 'linkers/link_stripped.json'))
for fn, ev in (('InvSquareRoot', 'head'), ('MatrixNormal', 'tail')):
    jf['functions'].append({'object': 'build/recon/syslib/psx/libgte/MSC02.c.o', 'function': fn, 'sdk': 'LIBGTE/' + fn,
                            'evidence': 'PsyQ 4.3 libgte MSC02.obj %s; the retail object text starts at VectorNormalS and ends with VectorNormalSS (strip_headtail.py)' % ev})
open(R + 'linkers/link_stripped.json', 'w', encoding='utf-8', newline='').write(json.dumps(jf, indent=1) + NL)
print(len(inv), len(mat))
