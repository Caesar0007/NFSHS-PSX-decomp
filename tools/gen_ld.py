#!/usr/bin/env python3
"""gen_ld.py -- THE CANONICAL `linkers/nfs4_recon.ld` GENERATOR (W67-A6).

Folds the three scratchpad generator legs into ONE owner:

  * scratchpad/w65a5/gen_ld.py  -- the base: text spine at implied retail
    bases, the .L LOCALIZE cut (`_jNN` jump-table pieces excluded), per-piece
    residual rodata placement, the .ldfrag data/sdata bodies;
  * scratchpad/w66a3/gen_ld.py  -- the widened `.bss` catch-all
    (`*(.bss.*)`): the canonical C_005/CDROM/BIOS/C_004 owners emit their
    disjoint retail `.bss` runs as separate nobits sections
    (.bss.st_<VA> / .bss.ds_<VA>); backup before the owner split: 3346a726;
  * scratchpad/w66a4/gen_ld.py  -- the `.rodata` legs: `.rodata_main`
    (rdata_80054548 residual pieces) + one `.roNNNN` region per anchored
    recon TU, from linkers/nfs4_recon.rodata_placement.json (the canonical
    copy of w66a4's rodownmap/mkplace output).

🔴 THE LANE-MARKER GUARD (the w66a4 §8 clobber-with-empty-git-diff hazard):
`linkers/nfs4_recon.ld` is a GENERATED SHARED FILE; two lanes' generators
overwrote each other wholesale and the clobber restored the file to HEAD, so
`git status` showed NOTHING.  This generator (a) stamps the file with its own
marker (the `GENERATED by <owner>` header line), and (b) REFUSES to overwrite
a file whose marker names an owner it does not recognise -- the recognised set
is itself + the superseded scratchpad legs (which all stamped
`scratchpad/w65a5/gen_ld.py`).  `--take-over` overrides, loudly.  Every
scratchpad gen_ld variant is superseded by this file: do not run them again.

The object census is RE-SCANNED from build/recon on every run (the 15E
stale-objdata hazard: a cached census has been measured to cost ~1% and, this
wave, to flip a spine row -- fecars vs fedialog).  `--objdata PATH` overrides
for A/B archaeology only and always prints the override loudly.

usage:
    python tools/gen_ld.py                # scan + write the script
    python tools/gen_ld.py --link         # ...and link (strict + multdef-ok)
    python tools/gen_ld.py --no-cut       # control: keep the _jNN pieces
    python tools/gen_ld.py --no-rodata    # control: skip the w66a4 .ro legs
    python tools/gen_ld.py --check-nfs4ld # verify the splat-lane nfs4.ld
                                          # piece lists (read-only; this tool
                                          # NEVER writes linkers/nfs4.ld)
"""
