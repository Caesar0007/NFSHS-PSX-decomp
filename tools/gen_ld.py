ROOT = Path(__file__).resolve().parents[1]      # tools/ -> repo root (16F!)
LD = r"C:/Tools/mips-ps1/mips/bin/mipsel-none-elf-ld.exe"
OBJDUMP = r"C:/Tools/mips-ps1/mips/bin/mipsel-none-elf-objdump"
OUTDIR = ROOT / "build" / "gen_ld"
TARGET = ROOT / "linkers" / "nfs4_recon.ld"
PLACEMENT = ROOT / "linkers" / "nfs4_recon.rodata_placement.json"
TEXT_START = 0x800128F0
DATA_START = 0x8010CCD4
SDATA_START = 0x8013C54C
OVERLAY_START = 0x80010000
FRONT_RODATA_STEM = "rdata_80010000"
MAIN_RODATA_STEM = "rdata_80054548"
MAIN_RODATA_START = 0x80054548
MAIN_RODATA_END = 0x8005797C


def source_owner_link_errors(stderr):
    """P906: --noinhibit-exec can return success despite ld ASSERT failures.

    These assertions are our exact storage contracts, not tolerated legacy
    blob-duplicate diagnostics. Never report a candidate owner link as valid
    merely because GNU ld still wrote an output image. No output is patched.
    """
    messages = ('native source data symbol address mismatch', 'native source data pointer target mismatch',
                'source data owner size mismatch', 'native zero owner size mismatch',
                'native auxiliary source window mismatch')
    return [line for line in stderr.splitlines() if any(message in line for message in messages)]

MARKER = "tools/gen_ld.py"
# markers this generator recognises as its own lineage and may overwrite;
# every scratchpad leg stamped the w65a5 string verbatim.
SUPERSEDED = {"scratchpad/w65a5/gen_ld.py"}
MARKER_RE = re.compile(r"GENERATED by (\S+)")

VA_RE = re.compile(r"/\*\s*([0-9A-Fa-f]+)\s+([0-9A-Fa-f]{8})\s")
CUT = "--no-cut" not in sys.argv


def arg_value(flag):
    if flag in sys.argv:
        i = sys.argv.index(flag)
        assert i + 1 < len(sys.argv), f"{flag} needs a value"
        return sys.argv[i + 1]
    return None


def marker_guard():
    """refuse to clobber another lane's generated file (w66a4 §8)."""
    if not TARGET.exists():
        return
    head = TARGET.read_text(errors="replace")[:400]
    m = MARKER_RE.search(head)
    owner = m.group(1).rstrip(".,)") if m else "<no marker at all>"
    if owner == MARKER or owner in SUPERSEDED:
        return
    if "--take-over" in sys.argv:
        print(f"[marker] TAKE-OVER: overwriting a file stamped by {owner}")
        return
    sys.exit(f"REFUSING to overwrite {TARGET}: its marker names {owner!r}, "
             f"which this generator does not own (recognised: {MARKER} + "
             f"{sorted(SUPERSEDED)}).  Re-run with --take-over only if that "
             f"lane is really dead.")


# ------------------------------------------------------------- object census
HDRRE = re.compile(r"^(\S+):\s+file format")
SYMRE = re.compile(r"^([0-9a-f]{8})\s(.{7})\s+(\S+)\s+([0-9a-f]{8})\s(.*)$")
SECRE = re.compile(r"^\s*\d+\s+(\S+)\s+([0-9a-f]{8})\s+")


def scan():
    """fresh {obj: {syms:[{off,sec,name}], secs:{}}} census of build/recon
    (the shape scratchpad/w66a4/scan.py produced, minus the reloc dump the
    generator never reads).  Batched objdump; empty output is a hard exit."""
    # P881: source-data ownership must not admit a stale probe/renamed TU's
    # second backing cell. Match build.py/relink.py's live-source census,
    # rather than treating every surviving cache object as a project input.
    # This changes input selection only; no object or instruction is modified.
    sources = [*(ROOT / "recon").rglob("*.cpp"), *(ROOT / "recon").rglob("*.c")]
    objs = sorted(ROOT / "build" / (str(src.relative_to(ROOT)) + ".o")
                  for src in sources
                  if (ROOT / "build" / (str(src.relative_to(ROOT)) + ".o")).is_file())
    assert objs, "no build/recon objects -- run tools/build.py --no-link first"
    data = {}

    def batches(seq, n):
        for i in range(0, len(seq), n):
            yield seq[i:i + n]

    cur = None
    for b in batches(objs, 40):
        r = subprocess.run([OBJDUMP, "-t"] + [str(p) for p in b],
                           capture_output=True, text=True)
        assert r.stdout.strip(), "objdump -t empty batch -- vacuous scan refused"
        for ln in r.stdout.splitlines():
            m = HDRRE.match(ln)
            if m:
                cur = str(Path(m.group(1)).resolve().relative_to(ROOT)).replace("\\", "/")
                data.setdefault(cur, {"syms": []})
                continue
            m = SYMRE.match(ln)
            if m and cur:
                val, flags, sec, _size, name = m.groups()
                if sec in (".reginfo", ".MIPS.abiflags", ".pdr",
                           ".gnu.attributes", ".comment", ".mdebug.abi32"):
                    continue
                if " d " in flags or " df " in flags:
                    continue
                data[cur]["syms"].append({"off": int(val, 16), "sec": sec,
                                          "name": name.strip()})
    cur = None
    for b in batches(objs, 40):
        r = subprocess.run([OBJDUMP, "-h"] + [str(p) for p in b],
                           capture_output=True, text=True)
        for ln in r.stdout.splitlines():
            m = HDRRE.match(ln)
            if m:
                cur = str(Path(m.group(1)).resolve().relative_to(ROOT)).replace("\\", "/")
                data.setdefault(cur, {"syms": []})
                data[cur].setdefault("secs", {})
                continue
            m = SECRE.match(ln)
            if m and cur:
                data[cur].setdefault("secs", {})[m.group(1)] = int(m.group(2), 16)
    return data


def check_nfs4ld():
    """READ-ONLY verification of the splat-lane script: every cut blob's
    pieces appear in linkers/nfs4.ld exactly once, in ascending VA order per
    stem (the relink_nfs4ld.py transformations are all applied and stable, so
    'regenerating' the nfs4.ld leg is a byte-neutral no-op)."""
    ld = (ROOT / "linkers" / "nfs4.ld").read_text(errors="replace")
    dataroot = ROOT / "asm" / "data"
    stems = sorted({re.sub(r"_[rjo]\d\d\..*$", "", p.name)
                    for p in dataroot.glob("*_[rjo][0-9][0-9].*.s")})
    assert stems, "no cut blob pieces under asm/data -- nothing to verify?"
    # nfs4.ld references every object once per SECTION region (.rodata /
    # .data / .bss ...), so the unit of verification is the (piece, section)
    # reference: each present at most once, and within one section region a
    # stem's rNN / jNN / oNN subsequences each ascend (blob order == VA order;
    # r and j legitimately interleave, so only the per-letter order is law).
    refs = defaultdict(list)      # (stem, sec-context) -> [(pos, letter, num)]
    bad = 0
    npieces = 0
    for stem in stems:
        for p in sorted(dataroot.glob(f"{stem}_[rjo][0-9][0-9].*.s")):
            npieces += 1
            m = re.search(r"_([rjo])(\d\d)\.", p.name)
            letter, num = m.group(1), int(m.group(2))
            # SYM ownership seams may split one broad residual into named
            # input subsections (for example .data.r13_pre / _post) so a
            # typed owning TU can replace only the exact retail byte run.
            # Accept dotted section names here; the old `\.\w+` silently
            # ignored those linker rows and weakened this verification gate.
            for r in re.finditer(re.escape(f"build/asm/data/{p.name}.o(")
                                 + r"(\.[\w.]+)\)", ld):
                refs[(stem, r.group(1))].append((r.start(), letter, num))
            seen = ld.count(f"build/asm/data/{p.name}.o(")
            if seen == 0:
                print(f"  [nfs4.ld] {p.name}: NOT referenced at all")
                bad += 1
    for (stem, sec), rr in sorted(refs.items()):
        rr.sort()
        for letter in "rjo":
            nums = [n for _, lt, n in rr if lt == letter]
            if nums != sorted(nums):
                print(f"  [nfs4.ld] {stem} {sec}: {letter}NN pieces out of "
                      f"order: {nums}")
                bad += 1
            dups = {n for n in nums if nums.count(n) > 1}
            if dups:
                print(f"  [nfs4.ld] {stem} {sec}: duplicated {letter}NN "
                      f"pieces: {sorted(dups)}")
                bad += 1
    if bad:
        sys.exit(f"nfs4.ld piece verification FAILED ({bad} rows)")
    print(f"[nfs4.ld] verified -- {npieces} cut-blob pieces over {len(stems)} "
          f"stems: every piece referenced, no per-section duplicates, "
          f"per-letter blob order held (file untouched)")


def main():
    if "--check-nfs4ld" in sys.argv:
        check_nfs4ld()
        if len(sys.argv) == 2:
            return

    marker_guard()

    # ---------------------------------------------------------- retail VAs
    vas, dup = {}, set()
    for ln in open(ROOT / "configs" / "symbol_addrs.txt", errors="replace"):
        m = re.match(r"(\S+?)\s*=\s*(0x[0-9A-Fa-f]+);\s*//\s*type:func", ln)
        if m:
            n, v = m.group(1), int(m.group(2), 16)
            if n in vas and vas[n] != v:
                dup.add(n)
            vas.setdefault(n, v)
    for n in dup:
        del vas[n]

    ov = arg_value("--objdata")
    if ov:
        print(f"[census] OVERRIDE: reading {ov} instead of a fresh scan "
              f"(A/B archaeology only -- the 15E stale-objdata hazard)")
        objdata = json.load(open(ov))
    else:
        objdata = scan()
        print(f"[census] fresh scan: {len(objdata)} objects")

    # --------------------------------------------------------- the text spine
    rows, nobase = [], []
    for o, d in objdata.items():
        tsz = d.get("secs", {}).get(".text", 0)
        if not tsz:
            continue
        bases = defaultdict(int)
        for s in d["syms"]:
            if s["sec"] != ".text":
                continue
            va = vas.get(s["name"])
            if va is None:
                m = re.match(r"(?:func|D|lbl)_([0-9A-Fa-f]{8})$", s["name"])
                if m:
                    va = int(m.group(1), 16)
            if va is not None:
                bases[va - s["off"]] += 1
        if bases:
            rows.append((max(bases.items(), key=lambda kv: kv[1])[0], tsz, o))
        else:
            nobase.append((tsz, o))
    rows.sort()

    placed, dropped, cur = [], [], 0
    for base, sz, o in rows:
        if base < cur:
            dropped.append((base, sz, o))
            continue
        placed.append((base, sz, o))
        cur = base + sz
    front = [r for r in placed if r[0] < TEXT_START]
    main_t = [r for r in placed if r[0] >= TEXT_START]

    # ------------------------------------------------ the front rodata pieces
    def piece_va(p):
        for ln in p.read_text(errors="replace").splitlines():
            m = VA_RE.search(ln)
            if m:
                return int(m.group(2), 16)
        raise AssertionError(f"{p.name}: no VA comment -- cannot place it")

    dataroot = ROOT / "asm" / "data"
    pieces = sorted(dataroot.glob(f"{FRONT_RODATA_STEM}_[rj][0-9][0-9].rodata.s"))
    whole = dataroot / f"{FRONT_RODATA_STEM}.rodata.s"
    front_ro = []
    if pieces:
        assert not whole.exists(), \
            "both the whole blob and its pieces exist -- refusing an ambiguous link"
        for p in pieces:
            front_ro.append((piece_va(p), p.name,
                             re.search(r"_(j)\d\d\.", p.name) is not None))
        front_ro.sort()
        assert front_ro[0][0] == OVERLAY_START, \
            f"first front-rodata piece is at {front_ro[0][0]:#x}, not the blob base"
    else:
        assert whole.exists(), f"no {FRONT_RODATA_STEM} blob or pieces in asm/data"
        front_ro.append((OVERLAY_START, whole.name, False))
    njtbl_front = sum(1 for _, _, j in front_ro if j)

    # every `_jNN` object of EITHER blob is dropped from the recon link
    jtbl_objs = set()
    if CUT:
        for p in sorted(dataroot.glob("*_j[0-9][0-9].*.s")):
            jtbl_objs.add(f"build/asm/data/{p.name}.o")

    # ------------------------------------------- the MAIN (resident) rodata
    mpieces = sorted(dataroot.glob(f"{MAIN_RODATA_STEM}_[rj][0-9][0-9].rodata.s"))
    mwhole = dataroot / f"{MAIN_RODATA_STEM}.rodata.s"
    main_ro = []
    if mpieces:
        assert not mwhole.exists(), \
            "both the whole blob and its pieces exist -- refusing an ambiguous link"
        for p in mpieces:
            main_ro.append((piece_va(p), p.name,
                            re.search(r"_(j)\d\d\.", p.name) is not None))
        main_ro.sort()
        assert main_ro[0][0] == MAIN_RODATA_START, \
            f"first main-rodata piece is at {main_ro[0][0]:#x}, not the blob base"
    else:
        assert mwhole.exists(), f"no {MAIN_RODATA_STEM} blob or pieces in asm/data"
        main_ro.append((MAIN_RODATA_START, mwhole.name, False))
    njtbl_main = sum(1 for _, _, j in main_ro if j)

    # the spine must not reach into the region (anti-vacuity for the region)
    for base, sz, o in placed:
        assert base >= MAIN_RODATA_END or base + sz <= MAIN_RODATA_START, \
            f"text object {o} at {base:#x}+{sz:#x} intersects the rodata-2 span"

    # ----------------------------------- the recon TUs' own .rodata windows
    RO_SPANS = [(OVERLAY_START, TEXT_START), (MAIN_RODATA_START, MAIN_RODATA_END)]
    recon_ro, recon_ro_out = [], []
    if PLACEMENT.exists() and "--no-rodata" not in sys.argv:
        for r in json.load(open(PLACEMENT)):
            row = (r["base"], r["end"], r["obj"], r["ok"])
            if any(lo <= r["base"] and r["end"] <= hi for lo, hi in RO_SPANS):
                recon_ro.append(row)
            else:
                recon_ro_out.append(row)
        recon_ro.sort()
        for a1, b1 in zip(recon_ro, recon_ro[1:]):
            assert a1[1] <= b1[0], \
                f"recon .rodata windows overlap: {a1[2]} {a1[0]:#x}..{a1[1]:#x} vs " \
                f"{b1[2]} {b1[0]:#x}..{b1[1]:#x}"
        assert recon_ro, "placement file present but no window inside a rodata span"

    # ---------------------------------------------------------- data fragments
    def frag(p):
        out = []
        for L in (ROOT / p).read_text().splitlines():
            s = L.strip()
            if s and not s.startswith("/*") and not s.startswith("*"):
                out.append("        " + s)
        return out

    sdata_lines = frag("linkers/nfs4_recon.sdata_8013C54C.ldfrag")
    data_lines = frag("linkers/nfs4_recon.data_8010CCD4.ldfrag")
    # NOTE: linkers/nfs4_recon.front_data.ldfrag is deliberately NOT read here
    # (unchanged from w65a5/w66a4: placing front_data is a separate,
    # separately-measured landing -- see the w66a4 continuation cursor).
    assert sdata_lines and data_lines, "empty .ldfrag -- refusing a vacuous script"

    # P881: native local-static storage is source-owned even though the full
    # frontend fragment above remains a separate layout task. Validate exact
    # payload and global/local offsets before removing the raw duplicate.
    # Protected-tool backups: scratchpad/p881_lasttick/backups.
    validate_source_data_owners(ROOT / "build")
    # P887: NOBITS reservations have no initialized payload to hash. Validate
    # their own source extent/symbol contract before native BSS placement.
    validate_source_zero_owners(ROOT / "build")
    # P907: a split compiler template can leave real, pre-existing raw
    # alignment bytes. Discover only explicitly validated retained pieces;
    # never append them to the shortened packed prefix at the wrong address.
    auxiliary_windows = source_auxiliary_windows()
    for window in auxiliary_windows:
        padding = window.get("retained_raw_padding")
        if padding:
            path = Path(padding["source"])
            assert path.parent.as_posix() == "asm/data" and padding["section"] == ".rodata"
            assert MAIN_RODATA_START <= padding["address"] < padding["address"] + padding["size"] <= MAIN_RODATA_END
            assert all(name != path.name for _,name,_ in main_ro)
            main_ro.append((padding["address"], path.name, False))
    main_ro.sort()

    fragment_sections = set()
    for L in sdata_lines + data_lines:
        for m in re.finditer(r"(build/\S+?\.o)\(([^)]*)\)", L):
            fragment_sections.update((m.group(1), section) for section in m.group(2).split())
    in_frag = set(fragment_sections)
    for owner in SOURCE_DATA_OWNERS:
        pair = ("build/" + owner["source"] + ".o", owner["section"])
        if owner.get("placement") == "fragment":
            assert pair in fragment_sections, f"source-data owner missing from fragment: {pair}"
        in_frag.add(pair)

    # P882: ownership is per input SECTION, not per object. Placing .data
    # must not suppress that TU's unplaced .sdata; the old object-only set
    # stranded those cells after .bss and produced real GP16 overflows.
    # Backup/diagnostic receipts: scratchpad/p882_gprel. This fixes omitted
    # section handling, not every section's still-unrecovered native address.

    extra_data, extra_sdata = [], []
    for o, d in sorted(objdata.items()):
        if not o.startswith("build/recon"):
            continue
        if d.get("secs", {}).get(".data", 0) and (o, ".data") not in in_frag:
            extra_data.append(f"        {o}(.data);")
        if d.get("secs", {}).get(".sdata", 0) and (o, ".sdata") not in in_frag:
            extra_sdata.append(f"        {o}(.sdata);")

    # --------------------------------------------------------- emit the ld
    L = []
    A = L.append
    A("/* linkers/nfs4_recon.ld -- GENERATED by tools/gen_ld.py (W67-A6 canonical;")
    A(" * folds scratchpad/{w65a5,w66a3,w66a4}/gen_ld.py -- those legs are dead).")
    A(" * The RECON-lane counterpart of linkers/nfs4.ld: the ~500 reconstructed")
    A(" * objects replace build/src/{front,main}.c.o, each .text placed at its")
    A(" * implied retail base (W62-A19 spine), .data/.sdata ordered by the three")
    A(" * per-blob-STEM .ldfrag files, everything else swept into trailing")
    A(" * catch-alls.")
    A(" *")
    A(" * .L LOCALIZE CUT (W65-A5): the splat blobs' `_jNN` jump-table pieces are")
    A(" * DUPLICATES of tables the recon TUs emit into their own .rodata")
    A(" * (scratchpad/w65a5/jtbl_own.txt: 48 byte-proven, 6 owned by containment")
    A(" * with a near-miss owner).  They are NOT linked here -- their `.L<VA>`")
    A(" * operands are src-lane local labels that no recon object defines.  Each")
    A(" * surviving residual piece is placed at its own retail VA, so dropping a")
    A(" * piece shifts nothing.")
    A(" * DO NOT EDIT BY HAND -- rerun tools/gen_ld.py. */")
    A("SECTIONS")
    A("{")
    A("    __romPos = 0;")
    A(f"    _gp = {SDATA_START:#x};")
    A("    PROVIDE(ticksA = ticks);")
    A("    header_ROM_START = __romPos;")
    A("    .header : AT(header_ROM_START) SUBALIGN(16)")
    A("    {")
    A("        build/asm/header.s.o(.data);")
    A("    }")
    A("    __romPos += SIZEOF(.header);")
    A("")
    A(f"    .rodata_front {OVERLAY_START:#x} : SUBALIGN(4)")
    A("    {")
    for va, name, isj in front_ro:
        if isj and CUT:
            A(f"        /* {va:#010x} {name} -- JUMP TABLE, recon TU owns it */")
            continue
        A(f"        . = {va - OVERLAY_START:#x};")
        A(f"        build/asm/data/{name}.o(.rodata);")
    A("    }")
    A("")
    A(f"    .rodata_main {MAIN_RODATA_START:#x} : SUBALIGN(4)")
    A("    {")
    for va, name, isj in main_ro:
        if isj and CUT:
            A(f"        /* {va:#010x} {name} -- JUMP TABLE, recon TU owns it */")
            continue
        A(f"        . = {va - MAIN_RODATA_START:#x};")
        A(f"        build/asm/data/{name}.o(.rodata);")
    A("    }")
    A("")
    A("    /* W66-A4: each anchored recon TU's OWN .rodata at its retail VA -- the")
    A("     * other half of the W65-A5 .L LOCALIZE cut.  Without these the TU's")
    A("     * jump table lands in .rodata_rest and every %hi/%lo(.rodata+N) switch")
    A("     * dispatch in its .text resolves to a non-retail address. */")
    for i, (base, end, o, ok) in enumerate(recon_ro):
        A(f"    .ro{i:04d} {base:#x} : SUBALIGN(4) {{ {o}(.rodata); }}"
          f"   /* {end - base} B{'' if ok else '  (anchor-only, E1-E5 not clean)'} */")
    # P907 auxiliary checks never select or split .rodata a second time.
    # Assert the actual selected source output, not merely the placement JSON.
    for window in auxiliary_windows:
        obj = "build/" + window["source"] + ".o"
        choices = [(i,base) for i,(base,end,o,ok) in enumerate(recon_ro) if o == obj]
        assert len(choices) == 1, "auxiliary window requires its native source rodata selection"
        i,base = choices[0]
        assert base == window["section_address"]
        assert objdata[obj]["secs"][".rodata"] == window["section_size"]
        A(f"    ASSERT(ADDR(.ro{i:04d}) == {base:#x} && SIZEOF(.ro{i:04d}) == {window['section_size']}, \"native auxiliary source window mismatch\")")
