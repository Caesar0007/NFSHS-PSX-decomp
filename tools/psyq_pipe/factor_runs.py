"""factor_runs.py [--apply] [--min-len N] [--min-users K] -- factor include runs that many flattened object headers
share into plain list headers (recon/lists/<name>.h: include lines only, no conditionals).
Greedy: repeatedly take the contiguous run of #include lines with the largest saving (occurrences-1)*length.
Verify afterwards with ichk.sh (identical preprocessed source)."""
import collections
import glob
import os
import re
import sys

apply = '--apply' in sys.argv
MINLEN = int(sys.argv[sys.argv.index('--min-len') + 1]) if '--min-len' in sys.argv else 6
MINUSE = int(sys.argv[sys.argv.index('--min-users') + 1]) if '--min-users' in sys.argv else 6
MAXLEN = 60
INC = re.compile(r'#include "([^"]+)"\s*$')

heads = {}
for p in glob.glob('recon/**/*.h', recursive=True):
    q = p.replace(os.sep, '/')
    if '/mod/' in q or 'game-mod' in q or 'syslib-mod' in q:
        continue
    s = open(q, encoding='latin-1', newline='').read()
    if 'generated by tools/psyq_pipe/flatten.py' not in s:
        continue
    nl = '\r\n' if '\r\n' in s else '\n'
    heads[q] = (s.split(nl), nl)


def runs(L):
    """maximal blocks of consecutive plain include lines: list of (start, [names])"""
    out = []
    i = 0
    while i < len(L):
        m = INC.match(L[i])
        if not m:
            i += 1
            continue
        j = i
        names = []
        while j < len(L) and INC.match(L[j]):
            names.append(INC.match(L[j]).group(1))
            j += 1
        out.append((i, names))
        i = j
    return out


made = []
used_names = set()
while True:
    cnt = collections.Counter()
    for q, (L, nl) in heads.items():
        seen = set()
        for st, names in runs(L):
            n = len(names)
            for a in range(n):
                for ln in range(MINLEN, min(MAXLEN, n - a) + 1):
                    key = tuple(names[a:a + ln])
                    if key not in seen:       # count a run once per header
                        seen.add(key)
                        cnt[key] += 1
    best = None
    bestgain = 0
    for key, c in cnt.items():
        if c >= MINUSE:
            g = (c - 1) * len(key)
            if g > bestgain or (g == bestgain and best is not None and len(key) > len(best)):
                best, bestgain = key, g
    if best is None or bestgain < MINLEN * (MINUSE - 1):
        break

    def stem(x):
        return re.sub(r'\W', '_', os.path.basename(x)[:-2])
    name = 'list_%s__%s' % (stem(best[0]), stem(best[-1]))
    k = 2
    base = name
    while name in used_names:
        name = '%s_%d' % (base, k)
        k += 1
    used_names.add(name)
    rel = 'lists/%s.h' % name
    n_rep = 0
    for q, (L, nl) in heads.items():
        i = 0
        while i <= len(L) - len(best):
            if all(INC.match(L[i + t]) and INC.match(L[i + t]).group(1) == best[t] for t in range(len(best))):
                L[i:i + len(best)] = ['#include "%s"' % rel]
                n_rep += 1
            i += 1
    made.append((rel, best, n_rep))
    if apply:
        os.makedirs('recon/lists', exist_ok=True)
        g = 'NFS4_LISTS_' + name.upper() + '_H'
        open('recon/' + rel, 'w', encoding='latin-1', newline='\n').write('\n'.join(
            ['/* %s -- an include run shared by %d object lists (factored by tools/psyq_pipe/factor_runs.py). */' % (name, n_rep),
             '#ifndef ' + g, '#define ' + g] + ['#include "%s"' % x for x in best] + ['#endif', '']))
if apply:
    for q, (L, nl) in heads.items():
        open(q, 'w', encoding='latin-1', newline='').write(nl.join(L))
saved = sum((n - 1) * len(b) for r, b, n in made)
print('list headers: %d   include lines saved: %d%s' % (len(made), saved, '' if apply else ' (dry run)'))
for r, b, n in made[:40]:
    print('  %3d users x %2d includes  %s' % (n, len(b), r))
