"""flatten_all.py <tu.cpp ...> -- run in the gate worktree. For each object: pick the first header it includes that
only this object uses (from the baseline .i traces), flatten it (flatten.py --auto --prune --write), check the
preprocessed source (ichk.sh); keep on 'same', restore the header otherwise."""
import glob
import os
import re
import subprocess
import sys

IB = 'C:/Temp/ibase'
users = {}
for p in glob.glob(IB + '/recon/**/*.i', recursive=True):
    if p.endswith('.preorigin.i'):
        continue
    tu = p[len(IB) + 1:-2].replace(chr(92), '/')
    seen = set()
    for line in open(p, encoding='latin-1'):
        m = re.match(r'# \d+ "([^"]+)"', line)
        if m:
            f = m.group(1).replace(chr(92) * 2, '/').replace(chr(92), '/')
            i = f.find('/recon/')
            if i >= 0:
                seen.add(os.path.normpath(f[i + 1:]).replace(chr(92), '/'))
    for f in seen:
        users.setdefault(f, set()).add(tu)


def sh(cmd):
    return subprocess.run(cmd, shell=True, capture_output=True, text=True)


REDO = '--redo' in sys.argv
sys.argv = [x for x in sys.argv if x != '--redo']
ok = bad = skip = 0
for tu in sys.argv[1:]:
    tu = tu.replace(chr(92), '/')
    src = open(tu, encoding='latin-1').read()
    d = os.path.dirname(tu)
    target = None
    for m in re.finditer(r'(?m)^#include "([^"]+)"', src):
        f = os.path.normpath(os.path.join(d, m.group(1))).replace(chr(92), '/')
        if not os.path.isfile(f):
            f2 = os.path.normpath(os.path.join('recon', m.group(1))).replace(chr(92), '/')
            if not os.path.isfile(f2):
                continue
            f = f2
        if f.startswith('recon/lib/') or '/shared/' in f or os.path.basename(f) in ('nfs4_new.h', 'link_stripped.h'):
            continue
        if users.get(f, set()) <= {tu} and re.search(r'^\s*#\s*(if|include)', open(f, encoding='latin-1').read(), re.M):
            target = f
            break
    if not target:
        print('skip  %s (no exclusive entry header)' % tu)
        skip += 1
        continue
    if 'generated by tools/psyq_pipe/flatten.py' in open(target, encoding='latin-1').read() and not REDO:
        print('done  %s' % tu)
        continue
    backup = open(target, 'rb').read()
    r = sh('python C:/Temp/flatten.py %s %s --auto --prune --write' % (tu, target))
    if r.returncode != 0:
        open(target, 'wb').write(backup)
        print('FAIL  %s  %s: %s' % (tu, os.path.basename(target), (r.stderr or r.stdout).strip().splitlines()[-1][:110]))
        bad += 1
        continue
    c = sh('bash C:/Temp/ichk.sh %s' % tu)
    line = next((x for x in c.stdout.splitlines() if x.startswith(('same', 'DIFF', 'NO-I'))), 'NO-RESULT')
    if line.startswith('same'):
        n = len(open(target, encoding='latin-1').read().split('\n'))
        print('OK    %s  %s (%d lines)' % (tu, os.path.basename(target), n))
        ok += 1
    else:
        open(target, 'wb').write(backup)
        print('DIFF  %s  %s: %s' % (tu, os.path.basename(target), line[:70]))
        bad += 1
print('flattened %d, not identical/failed %d, skipped %d' % (ok, bad, skip))
