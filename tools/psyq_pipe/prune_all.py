"""prune_all.py -- run prune_defs.py on every flattened header (pairs taken from the flatten logs)."""
import re
import subprocess
import sys

pairs = []
for log in sys.argv[1:]:
    for line in open(log, encoding='latin-1'):
        m = re.match(r'OK\s+(\S+)\s+(\S+) \(', line)
        if m:
            tu = m.group(1)
            src = open(tu, encoding='latin-1').read()
            d = tu.rsplit('/', 1)[0]
            import os
            for inc in re.findall(r'(?m)^#include "([^"]+)"', src):
                for base in (d, 'recon'):
                    f = os.path.normpath(os.path.join(base, inc)).replace(chr(92), '/')
                    if os.path.basename(f) == m.group(2) and os.path.isfile(f):
                        pairs.append((tu, f))
                        break
                else:
                    continue
                break
tot = rem = 0
for tu, h in pairs:
    if 'generated by tools/psyq_pipe/flatten.py' not in open(h, encoding='latin-1').read():
        continue
    r = subprocess.run(['python', 'C:/Temp/prune_defs.py', tu, h], capture_output=True, text=True)
    line = (r.stdout.strip().splitlines() or [r.stderr.strip()[-120:]])[-1]
    m = re.search(r'(\d+) of (\d+)', line)
    if m:
        rem += int(m.group(1))
        tot += int(m.group(2))
    else:
        print('ERR', tu, line)
print('headers %d, switch names removed %d of %d' % (len(pairs), rem, tot))
